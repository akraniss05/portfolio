const fs=require("node:fs");
const assert=require("node:assert/strict");
const {JSDOM}=require("jsdom");
(async()=>{
const html=fs.readFileSync("index.html","utf8");
const js=fs.readFileSync("app.js","utf8");
const dom=new JSDOM(html,{url:"https://example.test/portfolio/",runScripts:"outside-only",pretendToBeVisual:true});
const w=dom.window,d=w.document;
w.scrollTo=()=>{};
w.confirm=()=>true;
w.URL.createObjectURL=b=>{w._exportedBlob=b;return "blob:test"};
w.URL.revokeObjectURL=()=>{};
w.HTMLAnchorElement.prototype.click=function(){};
w.HTMLDialogElement.prototype.showModal=function(){this.setAttribute("open","")};
w.HTMLDialogElement.prototype.close=function(){this.removeAttribute("open")};
w.Blob=Blob;
w.TextEncoder=TextEncoder;
w.eval(js);
const sleep=ms=>new Promise(r=>setTimeout(r,ms));
await sleep(65);
const click=s=>{const n=d.querySelector(s);assert(n,s+" missing");n.click();return n};
assert(d.querySelector("#page-home.active"),"home not active");
assert.equal(d.querySelectorAll("#homeTemplates .template-card").length,3);
click('[data-page="templates"]');
assert.equal(d.querySelectorAll("#allTemplates .template-card").length,6);
click('#allTemplates button[data-template="creative"]');
assert(d.querySelector("#newProjectDialog").hasAttribute("open"),"new dialog not opened");
d.querySelector("#newProjectName").value="Test Creator";
d.querySelector("#createProjectForm").dispatchEvent(new w.Event("submit",{bubbles:true,cancelable:true}));
assert(d.querySelector("#page-editor.active"),"editor not displayed");
assert.match(d.querySelector("#portfolioCanvas").textContent,/Creative Designer/);
assert.equal(d.querySelectorAll("#portfolioCanvas [data-block]").length,6);
click('#portfolioCanvas [data-block]');
const name=d.querySelector('#inspectorContent [data-field="name"]');
assert(name,"hero inspector missing");
name.value="Nova Creator";
name.dispatchEvent(new w.Event("input",{bubbles:true}));
assert.match(d.querySelector("#portfolioCanvas").textContent,/Nova Creator/);
click('[data-add="quote"]');
assert.equal(d.querySelectorAll("#portfolioCanvas [data-block]").length,7);
click('#inspectorContent [data-op="duplicate"]');
assert.equal(d.querySelectorAll("#portfolioCanvas [data-block]").length,8);
click('#inspectorContent [data-op="delete"]');
assert.equal(d.querySelectorAll("#portfolioCanvas [data-block]").length,7);
click('#undoBtn');
assert.equal(d.querySelectorAll("#portfolioCanvas [data-block]").length,8);
click('[data-action="export-html"]');
const blob=w._exportedBlob;
assert(blob && blob.size>1000,"ZIP export failed");
const arr=new Uint8Array(await blob.arrayBuffer());
assert.equal(arr[0],0x50);
assert.equal(arr[1],0x4b);
click('[data-action="export-json"]');
assert(w._exportedBlob.type.includes("json"),"JSON export failed");
await sleep(550);
assert(w.localStorage.getItem("novalab-portfolio-backup"),"local persistence failed");
console.log("NovaLab Portfolio Builder browser runtime checks passed");
dom.window.close();
})().catch(e=>{console.error(e);process.exit(1)});
